-- Durable archive employee workflow; supplements existing OCR and matching tables.
CREATE TABLE IF NOT EXISTS a_archive_automation (
 report_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 revision INT NOT NULL,
 scope_code VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 data_mode ENUM('real','synthetic') NOT NULL,
 task_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 requested_by VARCHAR(64) NOT NULL,
 workflow_state VARCHAR(32) NOT NULL DEFAULT 'waiting_ocr',
 match_score INT NULL,
 match_status VARCHAR(32) NOT NULL DEFAULT 'pending',
 match_reason VARCHAR(1200) NOT NULL DEFAULT '',
 matched_fields JSON NOT NULL,
 conflict_fields JSON NOT NULL,
 decision_mode VARCHAR(24) NULL,
 confirmed_by VARCHAR(64) NULL,
 confirmed_at DATETIME(6) NULL,
 result_json JSON NULL,
 input_digest CHAR(64) NULL,
 assessment_batch_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
 last_error VARCHAR(1000) NULL,
 retry_after DATETIME(6) NULL,
 created_at DATETIME(6) NOT NULL,
 updated_at DATETIME(6) NOT NULL,
 PRIMARY KEY(report_id,revision),
 UNIQUE KEY uq_archive_automation_task(task_id),
 KEY ix_archive_automation_queue(data_mode,workflow_state,retry_after,updated_at),
 CONSTRAINT fk_archive_automation_task FOREIGN KEY(task_id) REFERENCES a_digital_worker_tasks(task_id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
