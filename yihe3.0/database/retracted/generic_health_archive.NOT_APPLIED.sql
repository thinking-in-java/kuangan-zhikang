CREATE TABLE a_health_file (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  owner_org_code VARCHAR(100) NOT NULL COMMENT '数据归属单位，服务端按登录权限赋值',
  storage_provider VARCHAR(24) NOT NULL COMMENT 'local/s3等，访问凭据不存本表',
  storage_key VARCHAR(512) NOT NULL COMMENT '服务端文件标识，不存临时签名URL',
  original_name VARCHAR(255) NOT NULL,
  content_type VARCHAR(100) NOT NULL,
  size_bytes BIGINT UNSIGNED NOT NULL,
  sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  scan_status VARCHAR(16) NOT NULL DEFAULT 'pending',
  uploaded_by VARCHAR(50) NOT NULL,
  uploaded_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  deleted_at DATETIME(3) NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_a_file_owner_id (owner_org_code,id),
  KEY ix_a_file_hash (owner_org_code,sha256),
  CONSTRAINT ck_a_file_size CHECK (size_bytes > 0),
