  archive_no VARCHAR(40) NOT NULL,
  employee_no VARCHAR(64) NOT NULL,
  active_employee_no VARCHAR(64) GENERATED ALWAYS AS (IF(deleted_at IS NULL,employee_no,NULL)) STORED,
