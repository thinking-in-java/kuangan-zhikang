  employee_name VARCHAR(100) NOT NULL,
  gender VARCHAR(12) NOT NULL DEFAULT 'unknown',
  birth_date DATE NULL,
  phone_cipher VARBINARY(512) NULL COMMENT '应用层加密手机号',
  phone_hmac BINARY(32) NULL COMMENT '服务端HMAC用于精确查询，密钥不入库',
  phone_last4 CHAR(4) NULL,
  identity_cipher VARBINARY(512) NULL COMMENT '应用层加密身份证',
  identity_hmac BINARY(32) NULL,
  identity_last4 CHAR(4) NULL,
  unit_code VARCHAR(100) NULL,
  unit_name VARCHAR(200) NULL,
  team_name VARCHAR(100) NULL,
  position_name VARCHAR(100) NULL,
  work_type VARCHAR(100) NULL,
  employment_date DATE NULL,
  source_code VARCHAR(24) NOT NULL,
  status VARCHAR(16) NOT NULL DEFAULT 'draft',
  risk_level VARCHAR(16) NOT NULL DEFAULT 'unassessed',
  risk_basis JSON NULL COMMENT '风险依据及规则版本，不由缺失数据推断低风险',
  completeness TINYINT UNSIGNED NOT NULL DEFAULT 0,
  missing_fields JSON NULL,
  data_version INT UNSIGNED NOT NULL DEFAULT 1 COMMENT '修改信息后递增，审核绑定此版本',
  published_revision_no INT UNSIGNED NULL COMMENT '最近正式归档版本，修改后仍可展示上一已发布版本',
  archived_at DATETIME(3) NULL,
  archived_by VARCHAR(50) NULL,
  row_version INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '乐观锁',
  created_by VARCHAR(50) NOT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_by VARCHAR(50) NOT NULL,
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  deleted_at DATETIME(3) NULL,
  deleted_by VARCHAR(50) NULL,
  delete_reason VARCHAR(500) NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_a_archive_owner_id (owner_org_code,id),
  UNIQUE KEY uk_a_archive_no (owner_org_code,archive_no),
  UNIQUE KEY uk_a_archive_employee (owner_org_code,active_employee_no),
  KEY ix_a_archive_queue (owner_org_code,deleted_at,status,risk_level,created_at),
  KEY ix_a_archive_name (owner_org_code,employee_name),
  KEY ix_a_archive_legacy (owner_org_code,legacy_user_code),
  KEY ix_a_archive_phone (owner_org_code,phone_hmac),
  KEY ix_a_archive_identity (owner_org_code,identity_hmac),
  KEY ix_a_archive_team (owner_org_code,unit_code,team_name,position_name),
  KEY ix_a_archive_source (owner_org_code,source_code,created_at),
  CONSTRAINT fk_a_archive_source FOREIGN KEY (source_code) REFERENCES a_health_source_type(code),
  CONSTRAINT ck_a_archive_name CHECK (CHAR_LENGTH(TRIM(employee_name)) > 0),
  CONSTRAINT ck_a_archive_employee CHECK (CHAR_LENGTH(TRIM(employee_no)) > 0),
  CONSTRAINT ck_a_archive_gender CHECK (gender IN ('unknown','male','female')),
  CONSTRAINT ck_a_archive_status CHECK (status IN ('draft','pending','approved','archived')),
  CONSTRAINT ck_a_archive_risk CHECK (risk_level IN ('unassessed','low','medium','high')),
  CONSTRAINT ck_a_archive_completeness CHECK (completeness BETWEEN 0 AND 100),
  CONSTRAINT ck_a_archive_version CHECK (data_version > 0),
  CONSTRAINT ck_a_archive_published CHECK (status <> 'archived' OR (published_revision_no IS NOT NULL AND archived_at IS NOT NULL AND archived_by IS NOT NULL)),
  CONSTRAINT ck_a_archive_delete CHECK (deleted_at IS NULL OR (deleted_by IS NOT NULL AND delete_reason IS NOT NULL AND CHAR_LENGTH(TRIM(delete_reason)) > 0))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='职工健康档案主表及当前管理状态';

